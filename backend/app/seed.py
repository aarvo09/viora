def seed() -> None:
    init_db()
    db = SessionLocal()
    try:
        staff = db.scalars(select(StaffUser)).first()
        if staff is None:
            staff = StaffUser(
                name="A. Sharma",
                email=STAFF_EMAIL,
                password_hash=hash_password(STAFF_PASSWORD),
                role="DSWO",
            )
            db.add(staff)
            db.flush()

        for person in PEOPLE:
            existing = db.scalars(select(User).where(User.uid == person["uid"])).first()
            if existing is not None:
                continue
            user = User(
                uid=person["uid"],
                display_name=person["name"],
                preferred_language=person["language"],
                preferred_channel=person["channel"],
                safe_contact_start=person["safe"][0],
                safe_contact_end=person["safe"][1],
                # Internal only. Never surfaced, never counted in aggregates.
                is_controlled_test=True,
            )
            db.add(user)
            db.flush()

            case = Case(
                user_id=user.id,
                case_ref=person["case_ref"],
                status="ACTIVE",
                legal_stage=person["stage"],
                assigned_staff_id=staff.id,
            )
            db.add(case)
            db.flush()

            for days_ago, signals, turns in person["history"]:
                when = datetime.now(timezone.utc) - timedelta(days=days_ago)

                interaction = Interaction(
                    case_id=case.id,
                    channel=person["channel"],
                    language=person["language"],
                    status="IN_PROGRESS",
                    turn_count=len(turns),
                    started_at=when,
                )
                db.add(interaction)
                db.flush()

                for seq, (role, content) in enumerate(turns, start=1):
                    db.add(
                        ConversationMessage(
                            interaction_id=interaction.id, seq=seq, role=role,
                            content=content, created_at=when,
                        )
                    )
                db.commit()

                # Real pipeline: scores, baselines, trends and factors are all
                # genuinely computed, not written in by hand.
                result = assessment.run_assessment(
                    db, interaction=interaction, raw_signals=signals,
                    model_id="seed", now=when,
                )
                logger.info(
                    "%-16s v%s  distress=%-5s threat=%-5s %-8s %s",
                    person["name"], result.report.report_version,
                    result.report.distress_score, result.report.threat_score,
                    result.risk_level, result.report.trend,
                )

        logger.info("")
        logger.info("Seed complete.")
        logger.info("  Dashboard login: %s / %s", STAFF_EMAIL, STAFF_PASSWORD)
        logger.info("  Profiles: %s", ", ".join(p["name"] for p in PEOPLE))
    finally:
        db.close()


if __name__ == "__main__":
    seed()
