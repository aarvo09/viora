def _signals(
    *,
    distress: dict[str, float] | None = None,
    threat: dict[str, float] | None = None,
    protective: dict[str, float] | None = None,
    crisis: dict[str, Any] | None = None,
    summary: str = "",
    turns: int = 6,
    avg_chars: float = 110.0,
    depth: str = "MEDIUM",
) -> dict[str, Any]:
    def block(d: dict[str, float] | None) -> dict[str, Any]:
        return {
            k: {"present": True, "intensity": v, "evidence": ""}
            for k, v in (d or {}).items()
        }

    return normalise(
        {
            "language_detected": "hi",
            "distress_signals": block(distress),
            "threat_signals": block(threat),
            "protective_signals": block(protective),
            "engagement": {"disclosure_depth": depth, "cooperativeness": 0.8},
            "crisis": crisis or {},
            "summary": summary,
        },
        turn_count=turns,
        avg_user_chars=avg_chars,
    )


